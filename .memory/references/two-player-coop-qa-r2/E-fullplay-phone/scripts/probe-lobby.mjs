import { chromium } from '/Users/bigtree/Git/ob-crash-game/node_modules/playwright/index.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const browser = await chromium.launch({ headless: true, args: ['--ignore-certificate-errors', '--use-gl=swiftshader', '--enable-webgl'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, ignoreHTTPSErrors: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
await page.goto('https://127.0.0.1:5205/', { waitUntil: 'load' });
await page.waitForTimeout(2500);
const cnt = await page.getByText('📱 모바일').count();
console.log('mobile button count:', cnt);
const vis = cnt ? await page.getByText('📱 모바일').first().isVisible() : null;
console.log('first visible:', vis);
const btns = await page.locator('button').allInnerTexts();
console.log('buttons:', JSON.stringify(btns.slice(0, 30)));
await page.screenshot({ path: path.join(OUT, 'probe-lobby.png') });
console.log('errors:', JSON.stringify(errs));
await browser.close();
